  await expect(canvas).toHaveAttribute('data-polar','true',{timeout:20000})
  await page.screenshot({path:'test-results/level3-map.png'})
  const rect=(await canvas.boundingBox())!
  await page.mouse.click(rect.x+rect.width*.5,rect.y+rect.height*.5)
  await expect(page.getByRole('dialog')).toContainText('Your 10 × 10 km landing area')
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'South Pole in detail',exact:true}).click()
